#!/usr/bin/env python3
"""Local quickstart. No API key, no network, no files written into the repo.

Builds a rough 3D previs, a four-second edit from synthetic clips, and a QA
report. Also runs the checker's built-in synthetic flash and cut self-check.
"""
from __future__ import annotations

import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "mixreel"
PREVIS = ROOT / "skills" / "mixreel-script" / "scripts" / "previs.py"
SCENE = ROOT / "skills" / "mixreel-script" / "assets" / "previs-product-orbit.example.json"


def run(args):
    completed = subprocess.run(args, capture_output=True, text=True)
    if completed.returncode != 0:
        raise SystemExit((completed.stderr or completed.stdout or "command failed").strip())
    return completed


def write_plan(directory):
    plan = {
        "version": 1,
        "duration": 4.0,
        "fps": 24,
        "illustration_count": 2,
        "music": {"asset": "music.wav", "duration": 4.0, "offset": 0.0, "events": []},
        "references": [],
        "reviews": {"storyboard": "pending", "style": "pending", "keyframes": "pending"},
        "shots": [],
    }
    for index, (asset, start) in enumerate((("a.mp4", 0.0), ("b.mp4", 2.0)), start=1):
        plan["shots"].append({
            "id": f"shot-{index}",
            "start": start,
            "end": start + 2.0,
            "function": "Show one beat of a product spot.",
            "source_evidence": "Synthetic color clip generated by the quickstart.",
            "keyframe_design": "Existing clip. No image generation.",
            "description": f"Hold {asset} for two seconds.",
            "opening": "First frame.",
            "ending": "Last frame.",
            "camera": {"behavior": "fixed", "start": "Fixed", "end": "Fixed"},
            "bindings": [],
            "keyframes": [f"frame-{index}"],
            "transition": {"type": "cut", "duration": 0},
            "clip": {"asset": asset, "in": 0, "duration": 2, "speed": 1},
        })
    path = directory / "plan.json"
    path.write_text(json.dumps(plan, indent=2) + "\n")
    return path


def main():
    for name in ("ffmpeg", "ffprobe"):
        if not shutil.which(name):
            raise SystemExit(f"{name} is required")
    out = Path(tempfile.mkdtemp(prefix="mixreel-demo-"))
    print(f"Demo directory: {out}", flush=True)
    previs = subprocess.run(
        [sys.executable, str(PREVIS), str(SCENE), "--out", str(out / "previs"),
         "--backend", "raster", "--shots", "S01,S02"],
        capture_output=True, text=True,
    )
    if previs.returncode != 0:
        raise SystemExit(previs.stderr or previs.stdout or "previs failed")
    for name, source in (("a", "testsrc2"), ("b", "smptebars")):
        run(["ffmpeg", "-v", "error", "-y", "-nostdin", "-f", "lavfi", "-i",
             f"{source}=size=360x640:rate=24:duration=2", "-an", "-c:v", "libx264",
             "-pix_fmt", "yuv420p", str(out / f"{name}.mp4")])
    run(["ffmpeg", "-v", "error", "-y", "-nostdin", "-f", "lavfi", "-i",
         "sine=frequency=440:sample_rate=48000:duration=4", str(out / "music.wav")])
    plan = write_plan(out)
    run([sys.executable, str(SKILL / "scripts" / "validate_plan.py"), str(plan)])
    run([sys.executable, str(SKILL / "scripts" / "render_edit.py"), str(plan),
         str(out / "master.mp4"), "--size", "360x640"])
    run([sys.executable, str(SKILL / "scripts" / "media_inspect.py"), "reference",
         str(out / "master.mp4"), str(out / "analysis")])
    qa = subprocess.run(
        [sys.executable, str(SKILL / "scripts" / "qa_check.py"), str(out / "master.mp4"),
         "--plan", str(plan), "--size", "360x640"],
        capture_output=True, text=True,
    )
    if qa.returncode not in (0, 1):
        raise SystemExit(qa.stderr or "quality checker failed")
    (out / "qa.json").write_text(qa.stdout)
    report = json.loads(qa.stdout)
    self_check = run([sys.executable, str(SKILL / "scripts" / "qa_check.py"), "--self-check"])
    summary = {
        "directory": str(out),
        "previs": str(out / "previs" / "previs.json"),
        "master": str(out / "master.mp4"),
        "qa": str(out / "qa.json"),
        "qa_exit_code": qa.returncode,
        "issues": report.get("issues", []),
        "self_check": json.loads(self_check.stdout),
        "note": "Synthetic quickstart. It does not call a model and it is not a client delivery.",
    }
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
